#!/usr/bin/env python3
"""CR-API-CAT-02: initial API contract population (deterministic, per G-10).

Emits one canonical API record (dea:api-<slug>) and one per-record README
for every Integration Interface record in the vendored inventory
(scripts/api_population_data.json, pinned to dea-catalog-integration-
interfaces at commit 35afd57443e4aab376dfc456cdef93fb39e7a22d, admitting
CR CR-IS-CAT-04B). Each record asserts exactly one typed relationship
instance: specifies -> the pinned Integration Interface id (OpenDEAM
v0.8.0 contract relationship, CR-021 D-4 disposition).

Conventions (G-10):
- stdlib only; no third-party imports;
- byte-idempotent: re-running over an already-populated tree rewrites the
  same bytes and touches nothing else;
- hard-fails on any inventory anomaly, id drift, or D-004/D-005 glyph
  embargo violation (no em dash, no en dash, no ellipsis, no triple
  semicolon in any emitted text).

Layout (docs/RECORD-STANDARD.md): entities/v1-alpha/<id>/<id>.yaml plus a
sibling README.md, where <id> is the canonical id (dea:api-<slug>).

CATALOG.yaml is NOT touched here: it is regenerated by
scripts/regenerate_catalog.py (machine-generated only; see the CR for the
exact reproduction commands).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / "scripts" / "api_population_data.json"

DATE = "2026-11-12"
REVIEW_DATE = "2027-11-12"
ADMITTING_CR = "CR-API-CAT-02"
SOURCE_CR = "CR-IS-CAT-04B"
ACTOR = "Emmanuel A. Otchere"

ID_RE = re.compile(r"^dea:api-[a-z0-9-]+$")
IF_ID_RE = re.compile(r"^dea:integration-interface-[a-z0-9-]+$")
SLUG_RE = re.compile(r"^[a-z0-9-]+$")

EMBARGO = ("\u2014", "\u2013", "\u2026")  # em dash, en dash, ellipsis (D-004)


class InventoryError(SystemExit):
    pass


def embargo_check(text: str, where: str) -> None:
    for glyph in EMBARGO:
        if glyph in text:
            raise InventoryError(f"{where}: D-004 embargo violation ({glyph!r})")
    if (";" * 3) in text:
        raise InventoryError(f"{where}: D-005 embargo violation (triple semicolon)")


def ystr(value: str) -> str:
    """Emit a YAML scalar. House style (RECORD-STANDARD §2): single-quoted
    with '' escaping; double-quoted when the prose contains ': '."""
    if ": " in value:
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    escaped = value.replace("'", "''")
    return f"'{escaped}'"


def humanize(slug: str) -> str:
    return slug.replace("-", " ")


def titleize(slug: str) -> str:
    return " ".join(w[:1].upper() + w[1:] for w in slug.split("-"))


KIND_TITLE = {
    "rest-api": "REST API",
    "file-transfer": "file transfer",
    "message-topic": "message topic",
    "event-stream": "event stream",
    "rpc": "RPC",
}

CONSUMER_TITLE = {
    "internal-machine": "internal machine",
    "external-partner": "external partner",
    "internal-application": "internal application",
    "internal-analyst": "internal analyst",
    "mixed": "mixed internal and external",
    "external-customer": "external customer",
}


def api_name(if_name: str) -> str:
    if if_name.endswith(" Interface"):
        return if_name[: -len(" Interface")] + " API Contract"
    if if_name.endswith(" API"):
        return if_name + " Contract"
    return if_name + " API Contract"


def build_texts(ifr: dict, pin: str) -> dict:
    kind = ifr["interface_kind"]
    if kind not in KIND_TITLE:
        raise InventoryError(f"{ifr['id']}: unknown interface_kind {kind!r}")
    consumer = ifr["consumer_class"]
    if consumer not in CONSUMER_TITLE:
        raise InventoryError(f"{ifr['id']}: unknown consumer_class {consumer!r}")
    sc = ifr["system_class"]
    sector = ifr["sector"]
    pattern = ifr["interaction_pattern"]
    description = (
        f"Vendor-neutral API contract record specifying the request and response "
        f"shape of the {ifr['name']} interaction boundary of the "
        f"{titleize(sc)} generic system class ({humanize(sector)} sector). "
        f"The contract fixes the {KIND_TITLE[kind]} message shapes and constraints "
        f"for {CONSUMER_TITLE[consumer]} consumers under the {pattern} interaction "
        f"pattern; the boundary itself is owned by the Integration Interface "
        f"catalogue record pinned for this population, which this contract "
        f"specifies per the CR-021 D-4 disposition. The substitutability test "
        f"passes: materially different vendor implementations can expose the "
        f"same contract shape. At least 3 distinct vendor systems corroborate "
        f"the shape as evidence only; no vendor product is canonical (per G-12)."
    )
    rationale = (
        f"The pinned Integration Interface record at commit {pin} is the canonical "
        f"boundary evidence: its generic system class binding and its 3 distinct "
        f"vendor corroborations ground this contract shape (evidence only; no "
        f"vendor product is canonical per G-12)."
    )
    source_and_evidence = (
        f"Metamodel clause (OpenDEAM v0.8.0 dea:entity-api, L5-integration, "
        f"contract entity per CR-021 D-4). Admitting CR {ADMITTING_CR} "
        f"(population, deterministic per G-10). Boundary evidence vendored from "
        f"{SOURCE_CR} at pin {pin}."
    )
    rel_rationale = (
        f"This contract specifies the request and response shape of the "
        f"{ifr['name']} boundary; the boundary is owned by the Integration "
        f"Interface catalogue record per the CR-021 D-4 disposition."
    )
    source_ref = (
        f"technehub-labs/dea-catalog-integration-interfaces@{pin}:{ifr['path']}"
    )
    return {
        "description": description,
        "rationale": rationale,
        "source_and_evidence": source_and_evidence,
        "rel_rationale": rel_rationale,
        "source_ref": source_ref,
    }


def emit_record(api_id: str, name: str, ifr: dict, t: dict) -> str:
    tags = [
        f"interface-kind:{ifr['interface_kind']}",
        f"interaction-pattern:{ifr['interaction_pattern']}",
        f"consumer-class:{ifr['consumer_class']}",
        f"sector:{ifr['sector']}",
        f"system-class:{ifr['system_class']}",
    ]
    lines = []
    lines.append(f"id: {ystr(api_id)}")
    lines.append("type: API")
    lines.append(f"name: {ystr(name)}")
    lines.append(f"description: {ystr(t['description'])}")
    lines.append("version: 1.0.0")
    lines.append("lifecycle_status: active")
    lines.append("tags:")
    for tag in tags:
        lines.append(f"- {ystr(tag)}")
    lines.append("evidence:")
    lines.append("  sources:")
    lines.append(f"  - kind: repository-path")
    lines.append(f"    reference: {ystr(t['source_ref'])}")
    lines.append(f"  rationale: {ystr(t['rationale'])}")
    lines.append("provenance:")
    lines.append("  ladder_passage:")
    for stage in ("candidate", "corroborated", "reviewed", "canonical"):
        lines.append(f"  - stage: {stage}")
        lines.append(f"    date: '{DATE}'")
        lines.append(f"    actor: {ystr(ACTOR)}")
    lines.append("governance:")
    lines.append(f"  functional_owner: {ystr(ACTOR)}")
    lines.append(f"  steward: {ystr(ACTOR)}")
    lines.append("  approval_status: approved")
    lines.append(f"  review_date: '{REVIEW_DATE}'")
    lines.append(f"  source_and_evidence: {ystr(t['source_and_evidence'])}")
    lines.append("relationships:")
    lines.append(f"  - id: {ystr('dea:relationship-' + ifr['slug'] + '-specifies')}")
    lines.append(f"    source_id: {ystr(api_id)}")
    lines.append(f"    target_id: {ystr(ifr['id'])}")
    lines.append("    relationship_type: specifies")
    lines.append("    direction: source-to-target")
    lines.append("    status: active")
    lines.append(f"    effective_from: '{DATE}'")
    lines.append(f"    rationale: {ystr(t['rel_rationale'])}")
    lines.append("    provenance:")
    lines.append("      type: manual")
    lines.append(f"      asserted_by: {ystr(ACTOR)}")
    lines.append(f"      asserted_at: '{DATE}'")
    lines.append("      verification_status: verified")
    lines.append("external_references:")
    for ext in ifr["external_references"]:
        lines.append(f"- system: {ystr(ext['system'])}")
        lines.append(f"  identifier: {ystr(ext['identifier'])}")
    lines.append("metadata:")
    lines.append(f"  created_at: '{DATE}'")
    lines.append(f"  updated_at: '{DATE}'")
    lines.append(f"  created_by: {ystr(ACTOR)}")
    lines.append("  status: active")
    return "\n".join(lines) + "\n"


def emit_readme(name: str, api_id: str, ifr: dict, t: dict, pin: str) -> str:
    vendors = "; ".join(e["system"] for e in ifr["external_references"])
    sc = ifr["system_class"]
    lines = []
    lines.append(f"# {name}")
    lines.append("")
    lines.append(f"> {t['description']}")
    lines.append("")
    lines.append("## Identity")
    lines.append("")
    lines.append(f"- Id: `{api_id}`")
    lines.append("- Type: API")
    lines.append("- Version: 1.0.0")
    lines.append("- Lifecycle status: active")
    lines.append(f"- Interface kind: {ifr['interface_kind']}")
    lines.append(f"- Interaction pattern: {ifr['interaction_pattern']}")
    lines.append(f"- Consumer class: {ifr['consumer_class']}")
    lines.append(f"- System class: {sc}")
    lines.append(f"- Sector: {ifr['sector']}")
    lines.append("- Catalog: dea:catalog-api-contracts")
    lines.append("")
    lines.append("## Evidence")
    lines.append("")
    lines.append(f"- Source (repository-path): `{t['source_ref']}`")
    lines.append(f"- Rationale: {t['rationale']}")
    lines.append(
        f"- Vendor corroboration (evidence only; no vendor product is canonical "
        f"per G-12): {vendors}"
    )
    lines.append("")
    lines.append("## Classification-or-relationships")
    lines.append("")
    lines.append(
        "This record asserts one typed relationship instance "
        "(direction source-to-target):"
    )
    lines.append("")
    lines.append("- Relationship type: specifies")
    lines.append(f"- Source: {api_id} (this record)")
    lines.append(f"- Target: {ifr['id']} (the {ifr['name']} integration interface)")
    lines.append(
        f"- Status: active; asserted {DATE} by {ACTOR}; verification verified"
    )
    lines.append("")
    lines.append(
        "Per the CR-021 D-4 disposition the contract specifies the interaction "
        "boundary; the boundary itself is owned by the Integration Interface "
        "catalogue record."
    )
    lines.append("")
    lines.append("## Provenance")
    lines.append("")
    lines.append(
        f"- Ladder passage (FOUNDATIONS D-4): candidate {DATE}; corroborated "
        f"{DATE}; reviewed {DATE}; canonical {DATE} (actor {ACTOR})."
    )
    lines.append(f"- Admitting CR: {ADMITTING_CR} (deterministic population per G-10).")
    lines.append(
        f"- Derived from the Integration Interface population admitted by "
        f"{SOURCE_CR} and vendored at pin {pin}."
    )
    lines.append("")
    lines.append("## Governance")
    lines.append("")
    lines.append(f"- Functional owner: {ACTOR}")
    lines.append(f"- Steward: {ACTOR}")
    lines.append("- Approval status: approved")
    lines.append(f"- Review date: {REVIEW_DATE}")
    lines.append(f"- Source and evidence: {t['source_and_evidence']}")
    lines.append(
        "- Change discipline: record changes land through CRs; a record edit "
        "regenerates CATALOG.yaml in the same PR (RECORD-STANDARD section 4)."
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    if not DATA.exists():
        print(f"FAIL: inventory not found at {DATA}", file=sys.stderr)
        return 1
    data = json.loads(DATA.read_text(encoding="utf-8"))
    pin = data["pin"]
    interfaces = data["interfaces"]
    if not interfaces:
        print("FAIL: inventory is empty", file=sys.stderr)
        return 1

    seen: set[str] = set()
    for ifr in interfaces:
        if not IF_ID_RE.match(ifr["id"]):
            print(f"FAIL: malformed interface id {ifr['id']!r}", file=sys.stderr)
            return 1
        if ifr["id"] in seen:
            print(f"FAIL: duplicate interface id {ifr['id']!r}", file=sys.stderr)
            return 1
        seen.add(ifr["id"])
        if not SLUG_RE.match(ifr["slug"]):
            print(f"FAIL: malformed slug {ifr['slug']!r}", file=sys.stderr)
            return 1
        if len(ifr.get("external_references") or []) < 3:
            print(
                f"FAIL: {ifr['id']} has fewer than 3 vendor corroborations",
                file=sys.stderr,
            )
            return 1

    entities_root = REPO / "entities" / "v1-alpha"
    emitted = 0
    for ifr in interfaces:
        api_id = "dea:api-" + ifr["slug"]
        if not ID_RE.match(api_id):
            print(f"FAIL: derived id {api_id!r} violates the canonical pattern", file=sys.stderr)
            return 1
        name = api_name(ifr["name"])
        if not 1 <= len(name) <= 200:
            print(f"FAIL: name length out of range for {api_id}", file=sys.stderr)
            return 1
        t = build_texts(ifr, pin)
        record_text = emit_record(api_id, name, ifr, t)
        readme_text = emit_readme(name, api_id, ifr, t, pin)
        embargo_check(record_text + readme_text, api_id)
        subdir = entities_root / api_id
        subdir.mkdir(parents=True, exist_ok=True)
        (subdir / f"{api_id}.yaml").write_text(record_text, encoding="utf-8")
        (subdir / "README.md").write_text(readme_text, encoding="utf-8")
        emitted += 1

    print(f"OK: emitted {emitted} API records under entities/v1-alpha/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
